//! Helpers shared by the integration tests: the fixtures, the bless switch and small builders.

#![allow(
    dead_code,
    reason = "each test binary uses its own part of the helpers"
)]

pub mod grounding;
pub mod loaded;

use std::path::PathBuf;

use oce_author::{
    Assignment, Block, Boundary, Connection, Endpoint, Identifier, Literal, ParamValue, Sequence,
    SequenceParameter, SignalType, parse_text,
};
use oce_diff::{Diff, DiffOptions, diff};

/// The environment variable that rewrites this crate's goldens.
pub const BLESS_SWITCH: &str = "OCE_BLESS_DIFF";

/// The worked examples of the diff note, by fixture name: (a) the site retune, its literal
/// variant, (b) the pressure request and (c) the plant reset.
pub const EXAMPLES: [&str; 4] = [
    "site_retune",
    "literal_retune",
    "pressure_request",
    "plant_reset",
];

/// The path of a file under `tests/fixtures/`.
pub fn fixture(relative: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures")
        .join(relative)
}

/// The text of a file under `tests/fixtures/`.
pub fn read(relative: &str) -> String {
    let path = fixture(relative);
    std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("read {}: {error}", path.display()))
}

/// Parse authoring text.
pub fn parse(text: &str) -> Sequence {
    parse_text(text).unwrap_or_else(|error| panic!("the text parses: {error:?}\n{text}"))
}

/// The two sides of a worked example.
pub fn example(name: &str) -> (Sequence, Sequence) {
    (
        parse(&read(&format!("examples/{name}.base.oce"))),
        parse(&read(&format!("examples/{name}.head.oce"))),
    )
}

/// The diff with the default options.
pub fn compare(base: &Sequence, head: &Sequence) -> Diff {
    diff(base, head, &DiffOptions::default())
}

/// The diff with the rename pass turned off.
pub fn compare_without_renames(base: &Sequence, head: &Sequence) -> Diff {
    let mut options = DiffOptions::default();
    options.renames = false;
    diff(base, head, &options)
}

/// Compare `actual` with the checked-in file at `path` byte for byte, or rewrite the file when
/// the bless switch is on.
pub fn compare_or_bless(path: &PathBuf, actual: &str) {
    if oce_bless::enabled(BLESS_SWITCH) {
        std::fs::write(path, actual).expect("write golden");
        return;
    }
    let expected = std::fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("read golden {}: {error}", path.display()));
    assert!(
        expected == actual,
        "{} differs from the generated bytes; rerun with {BLESS_SWITCH}=1 if the change is intended\n--- expected\n{expected}\n--- actual\n{actual}",
        path.display()
    );
}

/// An unchecked identifier.
pub fn id(name: &str) -> Identifier {
    Identifier::unchecked(name)
}

/// An empty sequence named `name`.
pub fn sequence(name: &str) -> Sequence {
    Sequence::new(id(name))
}

/// A block of `class` with literal assignments.
pub fn block(name: &str, class: &str, assignments: &[(&str, Literal)]) -> Block {
    let mut block = Block::new(id(name), class);
    for (parameter, value) in assignments {
        block.assignments.push(Assignment::new(
            id(parameter),
            ParamValue::Literal(value.clone()),
        ));
    }
    block
}

/// A connection from its two spellings.
pub fn link(source: &str, target: &str) -> Connection {
    Connection::new(Endpoint::parse(source), Endpoint::parse(target))
}

/// A boundary of type `value_type`.
pub fn boundary(name: &str, value_type: SignalType) -> Boundary {
    Boundary::new(id(name), value_type)
}

/// A Real sequence parameter.
pub fn real_parameter(name: &str, value: f64) -> SequenceParameter {
    SequenceParameter::new(id(name), SignalType::Real, Literal::Real(value))
}

/// The kebab-case `kind` and the `subject` of every entry of a section, as the JSON carries them.
pub fn kinds(section: &serde_json::Value) -> Vec<(String, String)> {
    section
        .as_array()
        .expect("a section is a list")
        .iter()
        .map(|entry| {
            (
                entry["kind"].as_str().expect("kind").to_owned(),
                entry["subject"].as_str().expect("subject").to_owned(),
            )
        })
        .collect()
}

/// The diff as a JSON value.
pub fn json(diff: &Diff) -> serde_json::Value {
    serde_json::from_str(&diff.to_json()).expect("the diff's JSON parses")
}
